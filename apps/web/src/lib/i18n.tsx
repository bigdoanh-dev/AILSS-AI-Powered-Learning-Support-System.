interface LanguageContextType {
  language: SupportedLanguage;
  setLanguage: (lang: SupportedLanguage) => void;
  t: (key: string, fallback?: string) => string;
  currentOption: LanguageOption;
  languages: LanguageOption[];
}

const LanguageContext = createContext<LanguageContextType>({
  language: "vi",
  setLanguage: () => {},
  t: (k, fb) => fb || k,
  currentOption: LANGUAGES[0],
  languages: LANGUAGES,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLangState] = useState<SupportedLanguage>(() => {
    try {
      const saved = localStorage.getItem("ailss-language") as SupportedLanguage;
      if (saved && LANGUAGES.some((l) => l.code === saved)) {
        return saved;
      }
    } catch {
      // Storage unavailable
    }
    return "vi";
  });

  const textRecordsRef = useRef<WeakMap<Node, { original: string; rendered: string }>>(new WeakMap());

  useEffect(() => {
    try {
      localStorage.setItem("ailss-language", language);
      document.documentElement.lang = language;
    } catch {
      // Storage unavailable
    }

    if (typeof window === "undefined" || !window.document) return;

    const dict = PHRASE_DICTIONARY[language];
    const records = textRecordsRef.current;

    const translateNode = (node: Node) => {
      // Skip scripts, styles, code blocks
      const parent = node.parentElement;
      if (!parent) return;
      const tag = parent.tagName.toLowerCase();
      if (tag === "script" || tag === "style" || tag === "code" || tag === "pre") return;

      if (node.nodeType === Node.TEXT_NODE) {
        const text = node.nodeValue;
        if (!text || !text.trim()) return;

        let record = records.get(node);
        if (!record) {
          record = { original: text, rendered: text };
          records.set(node, record);
        } else if (text !== record.rendered) {
          // React updated the text node. Treat its new value as the source text
          // instead of restoring the value from an earlier render.
          record.original = text;
          record.rendered = text;
        }

        const trimmed = record.original.trim();
        const replacement = language === "vi" ? undefined : dict?.[trimmed];
        const newText = replacement ? record.original.replace(trimmed, replacement) : record.original;
        if (node.nodeValue !== newText) {
          record.rendered = newText;
          node.nodeValue = newText;
        }
      }
    };

    const walk = (root: Node) => {
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let current = walker.nextNode();
      while (current) {
        translateNode(current);
        current = walker.nextNode();
      }
    };

    // Run initial scan
    walk(document.body);

    // Set up observer for dynamically added content
    const observer = new MutationObserver((mutations) => {
      for (const m of mutations) {
        if (m.type === "childList") {
          m.addedNodes.forEach((n) => walk(n));
        } else if (m.type === "characterData") {
          translateNode(m.target);
        }
      }
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true,
      characterData: true,
    });

    return () => {
      observer.disconnect();
    };
  }, [language]);

  const setLanguage = (lang: SupportedLanguage) => {
    setLangState(lang);
  };

  const t = (key: string, fallback?: string): string => {
    // 1. Direct translation key lookup
    const currentTable = TRANSLATIONS[language];
    if (currentTable && currentTable[key]) {
      return currentTable[key];
    }

    // 2. Phrase dictionary lookup (if key is a Vietnamese phrase)
    const dict = PHRASE_DICTIONARY[language];
    if (dict && dict[key]) {
      return dict[key];
    }

    // 3. Fallback phrase dictionary lookup
    if (fallback && dict && dict[fallback]) {
      return dict[fallback];
    }

    // 4. Fallback to Vietnamese translation table
    const defaultTable = TRANSLATIONS.vi;
    if (defaultTable && defaultTable[key]) {
      if (language !== "vi" && dict && dict[defaultTable[key]]) {
        return dict[defaultTable[key]];
      }
      return defaultTable[key];
    }

    return fallback || key;
  };

  const currentOption = LANGUAGES.find((l) => l.code === language) || LANGUAGES[0];

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, currentOption, languages: LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
